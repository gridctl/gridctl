package service

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"strings"
	"text/template"

	"github.com/gridctl/gridctl/pkg/project"
)

// generatedComment is the sentence both unit formats carry. Re-run the
// command to change a unit; hand edits are drift.
const generatedComment = "Generated by gridctl service install. Do not edit; re-run the command to change it."

// Render returns the supervisor unit text for spec. The same spec always
// produces the same bytes.
func Render(spec Spec) (string, error) {
	switch spec.Platform {
	case PlatformSystemd:
		return renderSystemd(spec)
	case PlatformLaunchd:
		return renderLaunchd(spec)
	default:
		return "", fmt.Errorf("unsupported service platform %q", spec.Platform)
	}
}

// Hash is the lockfile installed hash for unit text.
func Hash(text string) string {
	sum := sha256.Sum256([]byte(text))
	return project.HashScheme + hex.EncodeToString(sum[:])
}

func renderSystemd(spec Spec) (string, error) {
	data := struct {
		Comment     string
		Name        string
		Podman      bool
		ExecStart   string
		Environment []string
	}{
		Comment:   generatedComment,
		Name:      escapeSystemdBare(spec.Name),
		Podman:    spec.PodmanSocketDependency,
		ExecStart: quoteSystemdArgs(spec.Argv),
	}
	for _, kv := range spec.Env {
		data.Environment = append(data.Environment, kv.Key+"="+quoteSystemd(kv.Value))
	}
	var buf bytes.Buffer
	if err := systemdTmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("rendering systemd unit: %w", err)
	}
	return buf.String(), nil
}

// quoteSystemd applies systemd exec quoting: double quotes when the value
// contains whitespace, a quote, or a backslash; backslash and quote are
// escaped inside quotes; a literal % is always %%, quoted or not, because
// systemd treats % as a specifier.
func quoteSystemd(s string) string {
	needsQuote := strings.ContainsAny(s, " \t\n\r\"\\")
	var b strings.Builder
	if needsQuote {
		b.WriteByte('"')
	}
	for _, r := range s {
		switch r {
		case '\\', '"':
			if needsQuote {
				b.WriteByte('\\')
			}
			b.WriteRune(r)
		case '%':
			b.WriteString("%%")
		default:
			b.WriteRune(r)
		}
	}
	if needsQuote {
		b.WriteByte('"')
	}
	return b.String()
}

func quoteSystemdArgs(argv []string) string {
	parts := make([]string, len(argv))
	for i, arg := range argv {
		parts[i] = quoteSystemd(arg)
	}
	return strings.Join(parts, " ")
}

// escapeSystemdBare doubles % in a value that is not otherwise quoted,
// such as the Description line.
func escapeSystemdBare(s string) string {
	return strings.ReplaceAll(s, "%", "%%")
}

var systemdTmpl = template.Must(template.New("systemd").Parse(strings.TrimLeft(`
# {{.Comment}}
[Unit]
Description=gridctl gateway for stack {{.Name}}
Documentation=https://github.com/gridctl/gridctl/blob/main/docs/installation.md
{{- if .Podman}}
After=podman.socket
Wants=podman.socket
{{- end}}
StartLimitIntervalSec=600
StartLimitBurst=30

[Service]
Type=simple
ExecStart={{.ExecStart}}
Restart=on-failure
RestartSec=10
KillSignal=SIGTERM
TimeoutStopSec=30
{{- range .Environment}}
Environment={{.}}
{{- end}}

[Install]
WantedBy=default.target
`, "\n")))

func renderLaunchd(spec Spec) (string, error) {
	env := map[string]string{}
	for _, kv := range spec.Env {
		env[kv.Key] = kv.Value
	}
	keys := make([]string, 0, len(env))
	for key := range env {
		keys = append(keys, key)
	}
	sortStrings(keys)

	var body strings.Builder
	writePlistKey(&body, 1, "EnvironmentVariables")
	body.WriteString(indent(1) + "<dict>\n")
	for _, key := range keys {
		writePlistKey(&body, 2, key)
		writePlistString(&body, 2, env[key])
	}
	body.WriteString(indent(1) + "</dict>\n")
	writePlistKey(&body, 1, "ExitTimeOut")
	body.WriteString(indent(1) + "<integer>30</integer>\n")
	writePlistKey(&body, 1, "KeepAlive")
	body.WriteString(indent(1) + "<dict>\n")
	writePlistKey(&body, 2, "SuccessfulExit")
	body.WriteString(indent(2) + "<false/>\n")
	body.WriteString(indent(1) + "</dict>\n")
	writePlistKey(&body, 1, "Label")
	writePlistString(&body, 1, spec.Label)
	writePlistKey(&body, 1, "ProgramArguments")
	body.WriteString(indent(1) + "<array>\n")
	for _, arg := range spec.Argv {
		writePlistString(&body, 2, arg)
	}
	body.WriteString(indent(1) + "</array>\n")
	writePlistKey(&body, 1, "RunAtLoad")
	body.WriteString(indent(1) + "<true/>\n")
	writePlistKey(&body, 1, "StandardErrorPath")
	writePlistString(&body, 1, spec.LogPath)
	writePlistKey(&body, 1, "StandardOutPath")
	writePlistString(&body, 1, spec.LogPath)
	writePlistKey(&body, 1, "ThrottleInterval")
	body.WriteString(indent(1) + "<integer>10</integer>\n")
	writePlistKey(&body, 1, "WorkingDirectory")
	writePlistString(&body, 1, spec.Home)

	data := struct {
		Comment string
		Body    string
	}{
		Comment: generatedComment,
		Body:    body.String(),
	}
	var buf bytes.Buffer
	if err := launchdTmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("rendering launchd plist: %w", err)
	}
	return buf.String(), nil
}

func writePlistKey(b *strings.Builder, level int, key string) {
	b.WriteString(indent(level) + "<key>" + xmlEscape(key) + "</key>\n")
}

func writePlistString(b *strings.Builder, level int, value string) {
	b.WriteString(indent(level) + "<string>" + xmlEscape(value) + "</string>\n")
}

func indent(level int) string {
	return strings.Repeat("  ", level)
}

func xmlEscape(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '&':
			b.WriteString("&amp;")
		case '<':
			b.WriteString("&lt;")
		case '>':
			b.WriteString("&gt;")
		case '"':
			b.WriteString("&quot;")
		case '\'':
			b.WriteString("&apos;")
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func sortStrings(s []string) {
	// local sort to keep render free of a second import alias
	for i := 1; i < len(s); i++ {
		j := i
		for j > 0 && s[j] < s[j-1] {
			s[j], s[j-1] = s[j-1], s[j]
			j--
		}
	}
}

var launchdTmpl = template.Must(template.New("launchd").Parse(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- {{.Comment}} -->
<plist version="1.0">
<dict>
{{.Body}}</dict>
</plist>
`))
